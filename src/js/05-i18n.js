const I18n = {
  lang: 'es',
  init(){
    let saved = '';
    try { saved = (JSON.parse(localStorage.getItem('atelierroot.ui') || '{}') || {}).lang || ''; } catch(_){}
    const sys = (navigator.languages && navigator.languages[0]) || navigator.language || 'en';
    const forced = (location.search.match(/[?&]lang=(es|en)\b/) || [])[1];          // ?lang=en: this load only (links, tests)
    this.lang = forced || (LANGS_UI.includes(saved) ? saved : (/^es\b/i.test(sys) ? 'es' : 'en'));
    document.documentElement.lang = this.lang;
  },
  set(l){
    if (!LANGS_UI.includes(l) || l === this.lang) return;
    this.lang = l; document.documentElement.lang = l;
    try {
      const cur = JSON.parse(localStorage.getItem('atelierroot.ui') || '{}') || {};
      cur.lang = l; localStorage.setItem('atelierroot.ui', JSON.stringify(cur));
    } catch(_){}
    if (typeof Ui !== 'undefined' && Ui.data) Ui.data.lang = l;      // Ui.write() rewrites the whole object
    applyI18n(document);
    document.dispatchEvent(new CustomEvent('langchange', { detail: l }));
  }
};
// T('key', {n: 3}) -> text in the current language; {n} placeholders are replaced
function T(key, vars){
  const e = STR[key];
  let s = e ? (e[LANGS_UI.indexOf(I18n.lang)] || e[0]) : key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
  return s;
}
// a text already painted in one language -> the same entry in the current one (or the text unchanged)
function retranslate(text){
  for (const k in STR){ const e = STR[k]; if (e[0] === text || e[1] === text) return T(k); }
  return text;
}
function applyI18n(root){
  (root || document).querySelectorAll('[data-i18n],[data-i18n-title],[data-i18n-aria],[data-i18n-ph]').forEach(el => {
    const k = el.getAttribute('data-i18n');
    if (k){
      // replace only the element's own text, keeping icons and child spans
      const tn = [...el.childNodes].find(n => n.nodeType === 3 && n.nodeValue.trim());
      if (tn) tn.nodeValue = tn.nodeValue.replace(tn.nodeValue.trim(), T(k));
      else if (!el.children.length) el.textContent = T(k);
    }
    const a = el.getAttribute('data-i18n-title'); if (a) el.title = T(a);
    const b = el.getAttribute('data-i18n-aria'); if (b) el.setAttribute('aria-label', T(b));
    const c = el.getAttribute('data-i18n-ph'); if (c) el.placeholder = T(c);
  });
}
