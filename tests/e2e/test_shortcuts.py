"""VS Code style shortcuts: line selection, duplicate and delete lines, word wrap, multi-edit (Ctrl+D,
Ctrl+Shift+L, Shift+Alt+I), the Ctrl+K prefix, search in all documents, F2, the shortcut list,
the version next to «Saved» and «About» with the repository link."""
import os, sys, json
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import asyncio
from pathlib import Path
from playwright.async_api import async_playwright
from browser import URL, LAUNCH, engine
ENGINES = ('chromium', 'webkit')   # Firefox: synthetic key handling of contenteditable differs; see FAQ
errs = []; fails = []
def check(name, cond, extra=''):
  print(('OK   ' if cond else 'FALLO'), name, ('' if cond else '-> ' + str(extra)))
  if not cond: fails.append(name)
VERSION = json.loads((Path(__file__).resolve().parents[2] / 'package.json').read_text(encoding='utf-8'))['version']

async def setdoc(pg, html, text=None, at=0):
  """editor content + caret inside the first text node that contains `text` (offset `at` in it)"""
  await pg.evaluate("""([h, t, at]) => { ed.innerHTML = h; History.init(); Dirty.add(state.current); ed.focus();
    const w = document.createTreeWalker(ed, NodeFilter.SHOW_TEXT); let n; while ((n = w.nextNode())) if (!t || n.data.includes(t)) break;
    const r = document.createRange(); r.setStart(n, (t ? n.data.indexOf(t) : 0) + at); r.collapse(true); const s = getSelection(); s.removeAllRanges(); s.addRange(r); }""", [html, text, at])
async def html(pg): return await pg.evaluate("ed.innerHTML")
async def texts(pg): return await pg.evaluate("[...ed.children].map(b => b.textContent)")

async def main():
  async with async_playwright() as p:
    b = await engine(p).launch(**LAUNCH); pg = await b.new_page(viewport={'width': 1400, 'height': 860})
    pg.on('pageerror', lambda e: errs.append(str(e)))
    await pg.goto(URL); await pg.wait_for_timeout(700)

    print('=== selection and lines ===')
    await setdoc(pg, '<p>uno</p><p>dos</p><p>tres</p>', 'uno', 1)
    await pg.keyboard.press('Control+l')
    check('Ctrl+L selects the line', await pg.evaluate("getSelection().toString()") == 'uno')
    await pg.keyboard.press('Control+l')
    sel = await pg.evaluate("getSelection().toString()")
    check('Ctrl+L again adds the next line', 'uno' in sel and 'dos' in sel and 'tres' not in sel, sel)
    await setdoc(pg, '<p>alfa</p><p>beta</p>', 'beta', 2)
    await pg.keyboard.press('Shift+Alt+ArrowDown')
    check('Shift+Alt+Down duplicates the line', await texts(pg) == ['alfa', 'beta', 'beta'], await texts(pg))
    await pg.keyboard.press('Control+z')
    check('   ...and Ctrl+Z undoes it', await texts(pg) == ['alfa', 'beta'], await texts(pg))
    await setdoc(pg, '<p>alfa</p><p>beta</p>', 'alfa', 1)
    await pg.keyboard.press('Shift+Alt+ArrowUp')
    caret_in = await pg.evaluate("[...ed.children].indexOf(getSelection().anchorNode.parentElement.closest('p'))")
    check('Shift+Alt+Up duplicates and the cursor stays on the upper copy', await texts(pg) == ['alfa', 'alfa', 'beta'] and caret_in == 0, [await texts(pg), caret_in])
    await setdoc(pg, '<p>alfa</p><p>beta</p><p>gamma</p>', 'beta', 1)
    await pg.keyboard.press('Control+Shift+k')
    check('Ctrl+Shift+K deletes the line', await texts(pg) == ['alfa', 'gamma'], await texts(pg))
    await pg.keyboard.press('Alt+z')
    check('Alt+Z turns word wrap off in code blocks', await pg.evaluate("document.body.classList.contains('no-wrap') && getComputedStyle(document.getElementById('pvText')).whiteSpace === 'pre'"))
    await pg.keyboard.press('Alt+z')
    check('   ...and on again (remembered)', await pg.evaluate("!document.body.classList.contains('no-wrap') && JSON.parse(localStorage.getItem('atelieroot.ui')).noWrap === false"))

    print('=== multi-edit ===')
    await setdoc(pg, '<p>gato perro gato</p><p>un gato</p>', 'gato', 1)
    await pg.keyboard.press('Control+d')
    check('Ctrl+D selects the word', await pg.evaluate("getSelection().toString()") == 'gato')
    await pg.keyboard.press('Control+d')
    check('Ctrl+D again adds the next match', await pg.evaluate("ME.on && ME.items.length") == 2)
    await pg.keyboard.type('pez')
    check('typing edits both places', await texts(pg) == ['pez perro pez', 'un gato'], await texts(pg))
    await pg.keyboard.press('Backspace')
    check('Backspace deletes in both places', await texts(pg) == ['pe perro pe', 'un gato'], await texts(pg))
    await pg.keyboard.press('Escape')
    check('Esc leaves multi-edit', await pg.evaluate("!ME.on"))
    await pg.keyboard.press('Control+z')
    check('one Ctrl+Z undoes the typing in all places', await texts(pg) == ['gato perro gato', 'un gato'], await texts(pg))
    await setdoc(pg, '<p>gato perro gato</p><p>un gato</p>', 'perro', 1)
    await pg.evaluate("() => { const n = ed.firstChild.firstChild, r = document.createRange(); r.setStart(n, 0); r.setEnd(n, 4); const s = getSelection(); s.removeAllRanges(); s.addRange(r); }")
    await pg.keyboard.press('Control+Shift+l')
    check('Ctrl+Shift+L selects every match', await pg.evaluate("ME.items.length") == 3)
    await pg.keyboard.type('X')
    check('   ...and typing replaces all of them', await texts(pg) == ['X perro X', 'un X'], await texts(pg))
    await pg.keyboard.press('ArrowLeft')
    check('an arrow key leaves multi-edit', await pg.evaluate("!ME.on"))
    await setdoc(pg, '<p>uno</p><p>dos</p><p>tres</p>', 'uno', 0)
    await pg.evaluate("() => { const r = document.createRange(); r.setStart(ed.children[0].firstChild, 0); r.setEnd(ed.children[2].firstChild, 2); const s = getSelection(); s.removeAllRanges(); s.addRange(r); }")
    await pg.keyboard.press('Shift+Alt+i')
    await pg.keyboard.type(';')
    check('Shift+Alt+I: a cursor at the end of each selected line', await texts(pg) == ['uno;', 'dos;', 'tres;'], await texts(pg))
    await pg.keyboard.press('Escape')

    print('=== Ctrl+K prefix, list, search, F2 ===')
    await setdoc(pg, '<p>hola mundo</p>', 'mundo', 0)
    await pg.keyboard.press('Control+k'); await pg.keyboard.press('z'); await pg.wait_for_timeout(100)
    check('Ctrl+K Z: focus mode', await pg.evaluate("document.body.classList.contains('focus')"))
    await pg.keyboard.press('Escape'); await pg.wait_for_timeout(100)
    await pg.keyboard.press('Control+Shift+f'); await pg.wait_for_timeout(200)
    check('Ctrl+Shift+F no longer toggles focus mode', await pg.evaluate("!document.body.classList.contains('focus')"))
    check('Ctrl+Shift+F opens the search in all documents', await pg.evaluate("veil.classList.contains('show') && !!document.getElementById('gsq')"))
    await pg.keyboard.press('Escape')
    await setdoc(pg, '<p>hola mundo</p>', 'mundo', 0)
    await pg.keyboard.press('Control+k'); await pg.wait_for_timeout(1200)
    check('Ctrl+K alone still inserts a link (after a moment)', await pg.evaluate("veil.classList.contains('show') || !!document.querySelector('.menu.show, #linkPop.show, [id*=link].show')"))
    await pg.keyboard.press('Escape'); await pg.evaluate("veil.classList.remove('show')")
    await setdoc(pg, '<p>x</p>', 'x', 0)
    await pg.keyboard.press('Control+k'); await pg.keyboard.press('Control+s'); await pg.wait_for_timeout(150)
    n = await pg.evaluate("document.querySelectorAll('#kbl .kb-row').length")
    check('Ctrl+K Ctrl+S: the shortcut list with every shortcut', n == await pg.evaluate("KEYS.length") and n >= 30, n)
    await pg.fill('#kbq', 'Ctrl+D')
    check('   ...it can be filtered', await pg.evaluate("document.querySelectorAll('#kbl .kb-row').length") >= 1 and await pg.evaluate("document.querySelectorAll('#kbl .kb-row').length") < n)
    await pg.keyboard.press('Escape')
    await pg.click('#kbBtn'); await pg.wait_for_timeout(100)
    check('the toolbar button opens the list too', await pg.evaluate("!!document.getElementById('kbl')"))
    await pg.evaluate("closeCard()")
    # a second document with a unique word, then search all
    await pg.evaluate("""() => { const d = { id: uid(), type: 'doc', name: 'Recetas', mod: Date.now() }; state.tree.push(d); state.docs[d.id] = '<p>sopa de zanahoria y zanahoria</p>'; renderTree(); }""")
    await setdoc(pg, '<p>otro texto</p>', 'otro', 0)
    await pg.keyboard.press('Control+Shift+f'); await pg.fill('#gsq', 'zanahoria'); await pg.wait_for_timeout(300)
    got = await pg.evaluate("[document.querySelectorAll('#gsl .gs-item').length, document.getElementById('gsc').textContent]")
    check('search in all documents finds the other document', got[0] == 2 and '2' in got[1], got)
    await pg.keyboard.press('ArrowDown'); await pg.keyboard.press('Enter'); await pg.wait_for_timeout(300)
    got = await pg.evaluate("[findNode(state.current).name, F.open, F.i, $('#fq').value]")
    check('   ...Enter opens it on that match', got == ['Recetas', True, 1, 'zanahoria'], got)
    await pg.evaluate("closeFind()")
    await pg.keyboard.press('F2'); await pg.wait_for_timeout(150)
    check('F2 renames the current document', await pg.evaluate("veil.classList.contains('show') && !!card.querySelector('input') && card.querySelector('input').value === 'Recetas'"))
    await pg.evaluate("veil.classList.remove('show')")
    await setdoc(pg, '<p>ver [[Recetas]] hoy</p>', 'Recetas', 2)
    await pg.keyboard.press('F2'); await pg.wait_for_timeout(150)
    await pg.fill('#card input', 'Cocina'); await pg.keyboard.press('Enter'); await pg.wait_for_timeout(200)
    got = await pg.evaluate("[(() => { let r = null; walk(state.tree, x => { if (x.name === 'Cocina') r = x; }); return !!r })(), ed.textContent]")
    check('F2 on a [[link]] renames that document and updates the link', got[0] and '[[Cocina]]' in got[1], got)

    print('=== version and about ===')
    got = await pg.evaluate("[document.getElementById('ver').textContent, getComputedStyle(document.getElementById('ver')).display !== 'none']")
    check('the version is shown next to «Saved»', got == ['v' + VERSION, True], got)
    adj = await pg.evaluate("document.getElementById('saved').nextElementSibling === document.getElementById('ver')")
    check('   ...right after it', adj)
    await pg.click('#ver'); await pg.wait_for_timeout(100)
    links = await pg.evaluate("[...card.querySelectorAll('a[data-ext]')].map(a => a.getAttribute('href'))")
    check('the version opens «About» with the repository link', any(u.startswith('https://github.com/Arphael/') for u in links) and VERSION in await pg.evaluate("card.textContent"), links)
    await pg.evaluate("veil.classList.remove('show')")
    await pg.click('#brandBtn'); await pg.wait_for_timeout(100)
    check('the app name in the sidebar opens «About» too', await pg.evaluate("veil.classList.contains('show') && !!card.querySelector('a[data-ext]')"))
    opened = []
    await pg.evaluate("window.open = (u) => { window.__opened = u; return null; }")
    await pg.click('#card a[data-ext]'); await pg.wait_for_timeout(100)
    check('   ...the link opens outside the app', (await pg.evaluate("window.__opened || ''")).startswith('https://github.com/'))
    await pg.evaluate("veil.classList.remove('show')")
    await pg.evaluate("I18n.set('en')")
    check('texts follow the language', await pg.evaluate("document.getElementById('kbBtn').title.startsWith('Keyboard') && document.getElementById('ver').title.startsWith('Installed')"))
    await pg.evaluate("I18n.set('es')")
    check('no page errors', not errs, errs)
    await b.close()
  print('\n' + ('TODO OK' if not fails else f'{len(fails)} FALLOS: {fails}'))
  sys.exit(1 if fails else 0)
asyncio.run(main())
